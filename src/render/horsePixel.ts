/**
 * Hand-placed pixel art for horses: every grid below is a drawing, one character per pixel
 * (see design/art/pixel-art-bible.md). Three body templates (light, stock, draft) share one
 * character alphabet so a single drawing serves every coat by palette swap:
 *   coat  o outline · 1 shadow · 2 base · 3 highlight     white (pattern) O 5 6 7
 *   mane  M outline · m base · n highlight                 eye e + glint y · nostril/mouth x · muzzle z
 *   face-marking zones S star · T strip · U blaze · N snip · B bald (coat unless marked)
 *   legs  cannon q p P · pastern Q r R · coronet J k K · hoof g f F · feather V v w
 *   masks W white · s spot · r roan hair · d dapple · 0 flea-bite · D dorsal stripe
 *   gear  a outline · b shadow · c base · d highlight · h metal · I weave accent
 *         blanket i j k l · bedroll/cinch t u v w
 * Grids are [x, y, rows] in the 64×44 horse frame; leg grids are relative to the leg anchor.
 */
export type Grid = readonly [number, number, readonly string[]];
export type UpperVar = 'stand' | 'alert' | 'reach' | 'reach2' | 'graze' | 'low';
export type TailVar = 'hang' | 'swish' | 'flow' | 'high' | 'short' | 'kick';
export interface SideArt {
  upper: Record<UpperVar, Grid>;
  bridle: Record<UpperVar, Grid>;
  maneLong: Record<UpperVar, Grid>;
  front: Grid[];
  hind: Grid[];
  tail: Record<TailVar, Grid>;
  gear: Record<'blanket' | 'saddle' | 'bags' | 'bedroll', Grid>;
  rear: { img: Grid; gear: Record<'blanket' | 'saddle' | 'bags' | 'bedroll' | 'bridle', Grid>; angle: number; pivot: [number, number]; drop: number }[];
  lie: Grid;
  lieDy: number;
  masks: Record<string, Grid>;
  dorsal: Grid;
  anchors: { front: [number, number]; hind: [number, number]; farFront: [number, number]; farHind: [number, number]; seat: [number, number] };
}
export interface FBArt {
  body: Grid;
  head?: Grid;
  seat: [number, number];
  anchors: { nearDx: number; farDx: number; nearY: number; farY: number };
  bodySwish?: Grid;
  legs: Grid[]; // lift 0..2, left then right
  gear: Partial<Record<'blanket' | 'saddle' | 'bags' | 'bedroll' | 'bridle', Grid>>;
  masks: Record<string, Grid>;
}
export interface HorseArt {
  side: SideArt;
  front: FBArt;
  back: FBArt;
}

